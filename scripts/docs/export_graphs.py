"""Export the agent graph topologies as Mermaid, straight from the compiled graphs.

    python -m scripts.docs.export_graphs            # write docs/architecture/*.mmd
    python -m scripts.docs.export_graphs --check    # fail if the committed files are stale

The diagrams are generated rather than drawn because a hand-drawn architecture diagram
starts lying the first time someone adds an edge. These come out of
`StateGraph.compile()`, so they cannot disagree with the code — and the `--check` mode,
wired into a unit test, means a graph change that forgets to regenerate them fails the
build instead of quietly shipping a wrong picture.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path
from types import SimpleNamespace

_REPO_ROOT = Path(__file__).resolve().parents[2]
for _path in (_REPO_ROOT, _REPO_ROOT / "ai-orchestrator", _REPO_ROOT / "mcp-servers"):
    if str(_path) not in sys.path:
        sys.path.insert(0, str(_path))

OUTPUT_DIR = _REPO_ROOT / "docs" / "architecture"

_HEADER = (
    "%% Generated by scripts/docs/export_graphs.py — do not edit by hand.\n"
    "%% Regenerate with:  python -m scripts.docs.export_graphs\n"
)


def _with_header(mermaid: str) -> str:
    """Insert the provenance comment without displacing Mermaid's frontmatter.

    LangGraph emits a `---\\n…\\n---` config block, and Mermaid only honours
    frontmatter when it is the very first thing in the source. So the comment goes
    after it, not before.
    """
    if mermaid.startswith("---"):
        end = mermaid.find("\n---", 3)
        if end != -1:
            cut = mermaid.find("\n", end + 1) + 1
            return mermaid[:cut] + _HEADER + mermaid[cut:]
    return _HEADER + mermaid


def _stub_runtime() -> SimpleNamespace:
    """The agents only read limits and the HMAC key at construction time."""
    return SimpleNamespace(
        analyst_max_steps=8,
        analyst_timeout_seconds=60,
        analyst_proposal_ttl_seconds=300,
        hmac_proposal_key="x" * 32,
    )


def render_graphs() -> dict[str, str]:
    """Return {filename stem: mermaid source} for every agent graph."""
    from agents.analyst import Analyst
    from agents.auditor import Auditor

    runtime = _stub_runtime()
    llm = SimpleNamespace(model="n/a")
    agents = {
        "analyst-graph": Analyst(runtime=runtime, pool=None, llm=llm),
        "auditor-graph": Auditor(runtime=runtime, pool=None, llm=llm),
    }
    return {
        name: _with_header(agent._graph.get_graph().draw_mermaid())  # noqa: SLF001 — generator tooling
        for name, agent in agents.items()
    }


def write_graphs(target: Path = OUTPUT_DIR) -> list[Path]:
    target.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for stem, mermaid in render_graphs().items():
        path = target / f"{stem}.mmd"
        path.write_text(mermaid, encoding="utf-8")
        written.append(path)
    return written


def check_graphs(target: Path = OUTPUT_DIR) -> list[str]:
    """Return a list of human-readable drift complaints; empty means up to date."""
    problems: list[str] = []
    for stem, mermaid in render_graphs().items():
        path = target / f"{stem}.mmd"
        if not path.exists():
            problems.append(f"{path.relative_to(_REPO_ROOT)} is missing")
            continue
        if path.read_text(encoding="utf-8") != mermaid:
            problems.append(
                f"{path.relative_to(_REPO_ROOT)} is stale — the compiled graph has changed"
            )
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the committed diagrams match the code, write nothing")
    args = parser.parse_args(argv)

    if args.check:
        problems = check_graphs()
        for problem in problems:
            print(f"stale diagram: {problem}")
        if problems:
            print("\nregenerate with: python -m scripts.docs.export_graphs")
            return 1
        print("diagrams are up to date")
        return 0

    for path in write_graphs():
        print(f"wrote {path.relative_to(_REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
