"""Shared agent output schemas (Rule 1).

These Pydantic models define the structured outputs produced by the
analyst and auditor agents. Anything outside `packages/common/` MUST
import these — never redefine.

Master Patch Part 3 — every agent-output model now uses
`ConfigDict(extra="forbid", strict=True)`:
    * `extra="forbid"`  → an LLM emitting a smuggled field (e.g.
      "claim_data": {...}, "metadata": {...}) is rejected by the
      validation pipeline, which triggers a self-correcting retry.
    * `strict=True`     → no implicit "12" → 12 coercion, no None →
      "" fallbacks; the LLM must emit the right JSON types or fail.

Decimal fields opt out of strict (`Field(strict=False)`) because JSON
has no Decimal type — the LLM legitimately emits monetary amounts as
strings, and Pydantic's lenient Decimal validator parses those safely.
"""

from __future__ import annotations

from decimal import Decimal
from typing import Any, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field

from packages.common.enums import ClaimStatus, SeverityLabel


# ── Analyst output (B2.2) ──────────────────────────────────────────

class ClaimFlag(BaseModel):
    """A potential issue identified by the analyst.

    Flags ARE NOT decisions — the auditor reads these and decides outcome.
    """
    model_config = ConfigDict(extra="forbid", strict=True)

    code:     str    = Field(..., description="Machine code, e.g. 'policy_expired'")
    message:  str    = Field(..., description="Human-readable explanation")
    severity: Literal["info", "warning", "critical"]


class TriageReport(BaseModel):
    """Structured output of the analyst_agent.

    The auditor_agent (B2.3) consumes this report and produces a
    ClaimDecision (APPROVED / REJECTED / MANUAL_REVIEW).

    Fix E — extra="ignore" (was "forbid"):
        The analyst LLM may legitimately include auxiliary keys (e.g.
        "metadata", "confidence") that are not part of the schema.
        "forbid" caused false-positive retry loops for benign LLM output.
        "ignore" silently drops unknown keys while still enforcing all
        declared fields and their types (strict=True is preserved).
        The UNTRUSTED_INPUT boundary in the analyst system prompt is the
        primary defence against prompt-injection; schema loosening here
        prevents that defence from generating unnecessary retries.
        ClaimDecision and ClaimProcessingResult keep extra="forbid" because
        they are never generated by an LLM that may emit free-form output.
    """
    model_config = ConfigDict(extra="ignore", strict=True)

    status:   Literal["EXTRACTED", "EXTRACTION_FAILED", "USER_NOT_FOUND"]
    claim:    Optional[dict[str, Any]]    = None
    user:     Optional[dict[str, Any]]    = None
    policies: list[dict[str, Any]]        = Field(default_factory=list)
    flags:    list[ClaimFlag]             = Field(default_factory=list)
    summary:  str                         = ""


# ── Auditor output (B2.3) ──────────────────────────────────────────

class ClaimDecision(BaseModel):
    """Final decision produced by the auditor_agent.

    This is what gets shown to the user (Rule 6) and persisted via the
    claims MCP once user approval is granted (Phase C).

    Master Patch Part 3 — strict + forbid. Any LLM smuggling attempt
    (extra keys, type confusion) is rejected by validate_claim_decision
    and triggers the self-healing retry loop.
    """
    model_config = ConfigDict(extra="forbid", strict=True)

    decision:               ClaimStatus       # APPROVED | REJECTED | MANUAL_REVIEW
    claim_id:               Optional[str] = None   # external id from the PDF, e.g. "CASE-2026-0089"
    user_id:                int
    policy_id:              Optional[int] = None   # null if no eligible policy found
    severity_label:         SeverityLabel
    # JSON has no Decimal type; the LLM emits monetary amounts as strings
    # (see auditor prompt). Opt out of strict so the str→Decimal lenient
    # parser still works while every other field remains strict.
    reported_damage_amount: Optional[Decimal] = Field(default=None, strict=False)
    incident_date:          str               # ISO-8601
    incident_description:   str
    incident_location:      Optional[str] = None
    ai_reasoning:           str               # MUST be present (Rule 4)
    next_action:            Literal[
        "process_payout",
        "send_rejection_letter",
        "escalate_to_human",
    ]
    # persisted_claim_id is no longer set by the agent — the orchestrator
    # FastAPI handler calls create_claim directly after the agent returns
    # its TriageProposal, ensuring no autonomous DB mutation (Rule 6).


# ── Orchestration output (B3.2) ────────────────────────────────────

class ClaimProcessingResult(BaseModel):
    """Full pipeline output — what AgentRouter.process_claim() returns.

    Consumed by FastAPI (C1.4) and any other caller that needs the
    end-to-end result with timing + retry telemetry.
    """
    model_config = ConfigDict(extra="forbid", strict=True)

    pdf_path:           str
    pipeline_status:    Literal[
        "SUCCESS",
        "ANALYST_FAILED",
        "AUDITOR_FAILED",
    ]
    triage_report:      Optional[dict[str, Any]] = None
    claim_decision:     Optional[dict[str, Any]] = None
    analyst_retries:    int = 0
    auditor_retries:    int = 0
    analyst_latency_ms: int = 0
    auditor_latency_ms: int = 0
    total_latency_ms:   int = 0
    error_message:      Optional[str] = None
