"""The committed architecture diagrams must match the compiled graphs.

A hand-maintained diagram starts lying the first time someone adds an edge and forgets.
These are generated from `StateGraph.compile()`, and this test is what makes forgetting
to regenerate them a build failure rather than a silently wrong picture in the README.
"""
from __future__ import annotations

from scripts.docs.export_graphs import OUTPUT_DIR, check_graphs, render_graphs


def test_diagrams_are_up_to_date() -> None:
    problems = check_graphs()
    assert not problems, (
        "architecture diagrams are stale:\n  "
        + "\n  ".join(problems)
        + "\n\nregenerate with: python -m scripts.docs.export_graphs"
    )


def test_both_agent_graphs_are_exported() -> None:
    assert set(render_graphs()) == {"analyst-graph", "auditor-graph"}


def test_mermaid_frontmatter_stays_first() -> None:
    """Mermaid only honours its config block when it is the very first thing.

    The provenance comment is injected *after* that block for exactly this reason, so
    this guards against someone moving it back to the top.
    """
    for mermaid in render_graphs().values():
        assert mermaid.startswith("---"), "frontmatter must be the first thing in the file"
        assert "%% Generated by" in mermaid


def test_graphs_declare_the_expected_nodes() -> None:
    """The ReAct topology is a security invariant: every path must reach an end."""
    for name, mermaid in render_graphs().items():
        for node in ("think_act", "run_tools", "validate_sign", "escalate"):
            assert node in mermaid, f"{name} is missing the {node!r} node"
        assert "escalate --> __end__" in mermaid, (
            f"{name}: escalation must terminate the graph"
        )


def test_output_dir_is_inside_docs() -> None:
    assert OUTPUT_DIR.name == "architecture"
    assert OUTPUT_DIR.parent.name == "docs"
